import React, { useState } from 'react';
import { Database, Code2, Copy, Check, Terminal, FileCode } from 'lucide-react';
import { ColumnDefinition, TableDefinition } from '../types/supabase';

interface SchemaInspectorProps {
  definition: TableDefinition;
  supabaseUrl: string;
}

export const SchemaInspector: React.FC<SchemaInspectorProps> = ({
  definition,
  supabaseUrl
}) => {
  const [copiedSnippet, setCopiedSnippet] = useState<string | null>(null);

  const handleCopy = (text: string, id: string) => {
    navigator.clipboard.writeText(text);
    setCopiedSnippet(id);
    setTimeout(() => setCopiedSnippet(null), 2000);
  };

  const primaryKey = definition.primaryKey || 'id';

  // Generate SQL DDL or exact view definition
  const sqlDdl = definition.name === 'view_carregamento_expedicao'
    ? `-- 1. View Analítica de Expedição
create or replace view public.view_carregamento_expedicao as
select
  m.id as movimentacao_id,
  m.motosrista as motorista,
  m.placa,
  m.created_at as data_criacao,
  COALESCE(sum(p."qtd_Plt"), 0::bigint) as total_plt,
  COALESCE(sum(p.qtd_pct), 0::bigint) as total_pct,
  COALESCE(sum(p.somatotalproduto), 0::bigint) as total_unidades
from
  movimentacao m
  left join produtos p on p.id_item = m.id
group by
  m.id,
  m.motosrista,
  m.placa,
  m.created_at;

-- 2. Tabela de Itens Carregados por Carreta (public.produtos)
create table public.produtos (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  produto text null,
  lote integer null,
  id_item bigint null,
  "qtd_Plt" integer null,
  qtd_pct integer null,
  somatotalproduto integer null,
  constraint produtos_pkey primary key (id),
  constraint produtos_id_item_fkey foreign key (id_item) references movimentacao (id)
);

-- Conceder permissão de leitura para a API do Supabase
grant select on public.view_carregamento_expedicao to anon, authenticated, service_role;
grant select on public.produtos to anon, authenticated, service_role;`
    : `CREATE TABLE public.${definition.name} (\n` +
    definition.columns.map((c) => {
      let pgType = 'TEXT';
      if (c.type === 'integer') pgType = 'BIGINT';
      else if (c.type === 'number') pgType = 'NUMERIC(12,2)';
      else if (c.type === 'boolean') pgType = 'BOOLEAN';
      else if (c.type === 'timestamp') pgType = 'TIMESTAMPTZ DEFAULT now()';
      else if (c.type === 'json') pgType = 'JSONB';

      let constraints = '';
      if (c.isPrimaryKey) constraints += ' PRIMARY KEY';
      if (c.required && !c.isPrimaryKey) constraints += ' NOT NULL';

      return `  ${c.name} ${pgType}${constraints}`;
    }).join(',\n') +
    '\n);\n\n-- Ativar Row Level Security (RLS)\nALTER TABLE public.' + definition.name + ' ENABLE ROW LEVEL SECURITY;';

  // Generate JS code snippet
  const jsSnippet = `// Supabase JS Client
import { createClient } from '@supabase/supabase-js';

const supabase = createClient('${supabaseUrl}', 'SUA_ANON_KEY');

// 1. Consultar registros
const { data, error } = await supabase
  .from('${definition.name}')
  .select('*')
  .order('${primaryKey}', { ascending: false })
  .limit(20);

// 2. Inserir novo registro
const { data: newRow, error: insertError } = await supabase
  .from('${definition.name}')
  .insert([{ /* campos */ }])
  .select();`;

  // Generate cURL snippet
  const curlSnippet = `# Consultar via PostgREST API
curl -X GET "${supabaseUrl}/rest/v1/${definition.name}?select=*" \\
  -H "apikey: SUA_ANON_KEY" \\
  -H "Authorization: Bearer SUA_ANON_KEY"`;

  return (
    <div className="space-y-6">
      {/* Schema Structure Table */}
      <div className="p-5 rounded-xl bg-[#0d1424] border border-slate-800">
        <div className="flex items-center justify-between mb-4">
          <div className="flex items-center gap-2">
            <Database className="w-4 h-4 text-emerald-400" />
            <h4 className="text-xs font-semibold uppercase tracking-wider text-slate-300">
              Definição de Colunas: <span className="font-mono text-white lowercase">{definition.name}</span>
            </h4>
          </div>
          <span className="text-[11px] font-mono text-slate-500">
            {definition.columns.length} campos
          </span>
        </div>

        <div className="overflow-x-auto rounded-lg border border-slate-800/80">
          <table className="w-full text-left border-collapse text-xs">
            <thead>
              <tr className="border-b border-slate-800 bg-slate-900/90 text-slate-400 font-medium">
                <th className="py-2.5 px-3">Nome da Coluna</th>
                <th className="py-2.5 px-3">Tipo de Dado</th>
                <th className="py-2.5 px-3">Chave Primária</th>
                <th className="py-2.5 px-3">Obrigatório</th>
                <th className="py-2.5 px-3">Descrição / Formato</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-800/60 font-mono">
              {definition.columns.map((col) => (
                <tr key={col.name} className="hover:bg-slate-800/30">
                  <td className="py-2 px-3 text-slate-200 font-medium">{col.name}</td>
                  <td className="py-2 px-3 text-emerald-400">{col.type}</td>
                  <td className="py-2 px-3">
                    {col.isPrimaryKey ? (
                      <span className="text-emerald-400 font-bold">SIM (PK)</span>
                    ) : (
                      <span className="text-slate-600">-</span>
                    )}
                  </td>
                  <td className="py-2 px-3">
                    {col.required ? (
                      <span className="text-amber-400">NOT NULL</span>
                    ) : (
                      <span className="text-slate-500">NULL</span>
                    )}
                  </td>
                  <td className="py-2 px-3 text-slate-400 text-[11px]">
                    {col.description || col.format || '-'}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-2 gap-6">
        {/* SQL DDL */}
        <div className="p-5 rounded-xl bg-[#0d1424] border border-slate-800 flex flex-col">
          <div className="flex items-center justify-between mb-3">
            <div className="flex items-center gap-2">
              <FileCode className="w-4 h-4 text-cyan-400" />
              <h4 className="text-xs font-semibold uppercase tracking-wider text-slate-300">
                SQL DDL (PostgreSQL)
              </h4>
            </div>
            <button
              onClick={() => handleCopy(sqlDdl, 'sql')}
              className="text-[11px] text-slate-400 hover:text-slate-200 flex items-center gap-1 bg-slate-900 px-2.5 py-1 rounded border border-slate-800 transition-colors"
            >
              {copiedSnippet === 'sql' ? (
                <>
                  <Check className="w-3 h-3 text-emerald-400" />
                  <span>Copiado!</span>
                </>
              ) : (
                <>
                  <Copy className="w-3 h-3" />
                  <span>Copiar SQL</span>
                </>
              )}
            </button>
          </div>
          <pre className="p-4 rounded-xl bg-slate-950 border border-slate-800 text-xs font-mono text-slate-300 overflow-x-auto flex-1">
            {sqlDdl}
          </pre>
        </div>

        {/* REST & JS integration code */}
        <div className="p-5 rounded-xl bg-[#0d1424] border border-slate-800 flex flex-col space-y-4">
          <div>
            <div className="flex items-center justify-between mb-2">
              <div className="flex items-center gap-2">
                <Code2 className="w-4 h-4 text-emerald-400" />
                <h4 className="text-xs font-semibold uppercase tracking-wider text-slate-300">
                  Supabase JavaScript Client
                </h4>
              </div>
              <button
                onClick={() => handleCopy(jsSnippet, 'js')}
                className="text-[11px] text-slate-400 hover:text-slate-200 flex items-center gap-1 bg-slate-900 px-2.5 py-1 rounded border border-slate-800 transition-colors"
              >
                {copiedSnippet === 'js' ? <Check className="w-3 h-3 text-emerald-400" /> : <Copy className="w-3 h-3" />}
                <span>Copiar JS</span>
              </button>
            </div>
            <pre className="p-3.5 rounded-xl bg-slate-950 border border-slate-800 text-[11px] font-mono text-emerald-400/90 overflow-x-auto">
              {jsSnippet}
            </pre>
          </div>

          <div>
            <div className="flex items-center justify-between mb-2">
              <div className="flex items-center gap-2">
                <Terminal className="w-4 h-4 text-amber-400" />
                <h4 className="text-xs font-semibold uppercase tracking-wider text-slate-300">
                  PostgREST cURL Endpoint
                </h4>
              </div>
              <button
                onClick={() => handleCopy(curlSnippet, 'curl')}
                className="text-[11px] text-slate-400 hover:text-slate-200 flex items-center gap-1 bg-slate-900 px-2.5 py-1 rounded border border-slate-800 transition-colors"
              >
                {copiedSnippet === 'curl' ? <Check className="w-3 h-3 text-emerald-400" /> : <Copy className="w-3 h-3" />}
                <span>Copiar cURL</span>
              </button>
            </div>
            <pre className="p-3.5 rounded-xl bg-slate-950 border border-slate-800 text-[11px] font-mono text-amber-400/90 overflow-x-auto">
              {curlSnippet}
            </pre>
          </div>
        </div>
      </div>
    </div>
  );
};
